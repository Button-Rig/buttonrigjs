#!/usr/bin/env bash
# Regenerates theme.css and fonts/ from the Button Rig app, the same way the app builds
# /__buttonrig/theme.css (app/infrastructure/src/services/plugin_web_server/theme.rs): the
# br-tokens block of buttonrig-ui/style.css (data-theme -> data-br-theme), its @font-face rules
# (font URLs relative to this package), then plugin_web_server/components.css.
#
# Usage: scripts/sync-theme.sh [--check] [APP_DIR]
#   APP_DIR defaults to $BUTTONRIG_APP_DIR, else ../app next to this repo.
#   --check writes nothing and exits 1 when theme.css or fonts/ are out of date.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
check=0
app=""
for arg in "$@"; do
  case "$arg" in
    --check) check=1 ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) app="$arg" ;;
  esac
done
app="${app:-${BUTTONRIG_APP_DIR:-$root/../app}}"
style="$app/buttonrig-ui/style.css"
components="$app/infrastructure/src/services/plugin_web_server/components.css"
fonts="$app/buttonrig-ui/public/fonts"
for f in "$style" "$components" "$fonts"; do
  [ -e "$f" ] || { echo "sync-theme: $f not found (pass the app dir)" >&2; exit 2; }
done

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

{
  echo '/* Button Rig theme for plugin configurators and stylers. Dark by default; configurator.js sets data-br-theme="light" on <html> for the light theme. */'
  echo '/* Generated by scripts/sync-theme.sh from the Button Rig app. Do not edit. The app serves the same CSS as /__buttonrig/theme.css and injects it into configurator and styler pages; import this copy only for standalone development. */'
  awk '/\/\* br-tokens:end \*\//{on=0} on{print} /\/\* br-tokens:start \*\//{on=1}' "$style" \
    | sed 's/\[data-theme=/[data-br-theme=/g'
  echo
  echo '/* Hidden until configurator.js knows the theme (no dark flash in the light theme). */'
  echo 'html[data-br-theme-pending] { visibility: hidden; }'
  echo
  awk '/@font-face/{on=1} on{print} on && /}/{on=0}' "$style" | sed 's#public/fonts/#./fonts/#g'
  echo
  cat "$components"
} > "$tmp/theme.css"

grep -q -- '--br-accent:' "$tmp/theme.css" || { echo "sync-theme: no br-tokens block in $style" >&2; exit 2; }

mkdir -p "$tmp/fonts"
for name in $(grep -o '\./fonts/[^")]*' "$tmp/theme.css" | sed 's#\./fonts/##' | sort -u); do
  cp "$fonts/$name" "$tmp/fonts/$name"
done
[ -f "$fonts/IBM-Plex-OFL.txt" ] && cp "$fonts/IBM-Plex-OFL.txt" "$tmp/fonts/"

if [ "$check" = 1 ]; then
  if cmp -s "$tmp/theme.css" "$root/theme.css" && diff -rq "$tmp/fonts" "$root/fonts" >/dev/null 2>&1; then
    echo "sync-theme: theme.css and fonts/ are up to date"
    exit 0
  fi
  echo "sync-theme: theme.css or fonts/ are stale; run scripts/sync-theme.sh" >&2
  exit 1
fi

cp "$tmp/theme.css" "$root/theme.css"
rm -rf "$root/fonts"
cp -r "$tmp/fonts" "$root/fonts"
echo "sync-theme: wrote theme.css and fonts/ from $app"
